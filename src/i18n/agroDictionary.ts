export function lookupLocalizedAgro(
  categoryOrDict: 'crops' | 'soilTypes' | 'growthStages' | 'seasons' | 'waterSources' | Record<string, Partial<Record<LanguageCode, string>>>,
  key: string,
  lang: LanguageCode
): string {
  if (!key) return '';
  let dict: Record<string, Partial<Record<LanguageCode, string>>>;
  if (typeof categoryOrDict === 'string') {
    switch (categoryOrDict) {
      case 'crops':
        dict = LOCALIZED_CROPS;
        break;
      case 'soilTypes':
        dict = LOCALIZED_SOIL_TYPES;
        break;
      case 'growthStages':
        dict = LOCALIZED_STAGES;
        break;
      case 'seasons':
        dict = LOCALIZED_SEASONS;
        break;
      case 'waterSources':
        dict = LOCALIZED_WATER_SOURCES;
        break;
      default:
        dict = LOCALIZED_CROPS;
    }
  } else {
    dict = categoryOrDict;
  }

  const lower = key.toLowerCase().trim();
  for (const [k, translations] of Object.entries(dict)) {
    if (lower.includes(k) || k.includes(lower)) {
      return translations[lang] || translations.en || key;
    }
  }
  return key;
}
