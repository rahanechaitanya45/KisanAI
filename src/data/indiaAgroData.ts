export const INDIAN_STATES_AND_DISTRICTS = INDIA_AGRO_STATES.map((state) => ({
  state: state.name,
  code: state.code,
  districts: state.districts.map((d) => d.name),
}));

export function getDistrictsForState(stateName: string): DistrictInfo[] {
  const found = INDIA_AGRO_STATES.find((s) => s.name.toLowerCase() === stateName.toLowerCase());
  return found ? found.districts : [];
}

export function getDistrictInfo(stateName: string, districtName: string): DistrictInfo | undefined {
  const stateDistricts = getDistrictsForState(stateName);
  return stateDistricts.find(
    (d) =>
      d.name.toLowerCase() === districtName.toLowerCase() ||
      (d.nameMr && d.nameMr === districtName) ||
      (d.nameHi && d.nameHi === districtName)
  );
}

export function formatDistrictLabel(district: DistrictInfo, lang?: string): string {
  if (lang === 'mr' && district.nameMr) {
    return `${district.nameMr} (${district.name})`;
  }
  if (district.nameMr) {
    return `${district.name} (${district.nameMr})`;
  }
  return district.name;
}

